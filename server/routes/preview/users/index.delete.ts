// Копия DELETE /api/users (удаление своего аккаунта). В демо — безопасный no-op:
// демо-пользователь общий на весь процесс, реально его не трогаем, иначе поломается
// сессия для всех зрителей демо. Клиент после ответа сам уходит на главную.
export default defineEventHandler((event) => {
    setResponseStatus(event, 204);
});
